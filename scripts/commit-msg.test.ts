import assert from 'node:assert/strict';
import { test } from 'node:test';
import { problems } from './commit-msg.ts';

test('conventional titles pass', () => {
  for (const ok of [
    'feat(site): add llms.txt',
    'fix: keep the camera still',
    'refactor(figures)!: move the rig into its own file',
    'docs(openspec): record the change\n\nWhy it matters.',
  ])
    assert.deepEqual(problems(ok), [], ok);
});

test('git-made subjects pass', () => {
  for (const ok of ['Revert "feat(site): add llms.txt"', 'fixup! fix: x', 'squash! feat: y'])
    assert.deepEqual(problems(ok), [], ok);
});

test('free-form titles fail with the expected format', () => {
  assert.match(problems('arreglos varios')[0], /type\(scope\): subject/);
  assert.equal(problems('Feat: capital type').length, 1);
});

test('AI attribution fails', () => {
  for (const bad of [
    'feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>',
    'fix: y\n\n🤖 Generated with Claude Code',
    'docs: z\n\nGenerated by Copilot',
  ])
    assert.ok(
      problems(bad).some((p) => /attribution/.test(p)),
      bad,
    );
});

test('people as co-authors and comment lines are fine', () => {
  assert.deepEqual(problems('feat: x\n\nCo-Authored-By: Ana Ruiz <ana@example.com>'), []);
  assert.deepEqual(problems('feat: x\n# Generated with Claude (git comment, stripped)'), []);
});
